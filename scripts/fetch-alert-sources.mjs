#!/usr/bin/env node
/** Probe public alert sources; write changeEvents.generated.ts. No monograph full text. */
import { writeFileSync, existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outTs = join(root, "src/data/changeEvents.generated.ts");
const now = new Date().toISOString();
const day = now.slice(0, 10);

const SOURCES = [
  { key: "ich-database", name: "ICH", url: "https://database.ich.org/", pharmacopoeia: "ICH" },
  { key: "fda-nitrosamine", name: "FDA nitrosamine", url: "https://www.fda.gov/regulatory-information/search-fda-guidance-documents/control-nitrosamine-impurities-human-drugs", pharmacopoeia: "FDA" },
  { key: "ema-nitrosamine", name: "EMA nitrosamine", url: "https://www.ema.europa.eu/en/human-regulatory/post-authorisation/referral-procedures-human-medicines/nitrosamine-impurities", pharmacopoeia: "EMA" },
  { key: "edqm-crs", name: "EDQM CRS", url: "https://crs.edqm.eu/", pharmacopoeia: "EP" },
  { key: "chp-portal", name: "ChP", url: "https://ydz.chp.org.cn/", pharmacopoeia: "ChP" },
];

async function probe(url) {
  const ctrl = new AbortController();
  const t = setTimeout(() => ctrl.abort(), 8000);
  try {
    const res = await fetch(url, { method: "GET", redirect: "follow", signal: ctrl.signal, headers: { "User-Agent": "pharmacopoeia-mvp-fetch-alerts/0.1" } });
    clearTimeout(t);
    return { ok: res.ok, status: res.status };
  } catch (e) {
    clearTimeout(t);
    return { ok: false, status: 0, error: String(e.message || e) };
  }
}

const results = [];
for (const s of SOURCES) {
  const r = await probe(s.url);
  results.push({ ...s, ...r });
  console.log(s.key, r.ok ? `OK ${r.status}` : `FAIL ${r.status || r.error}`);
}

const probeEvents = results.map((r) => `  {
    id: "ce-probe-${r.key}-${day.replace(/-/g, "")}",
    date: "${day}",
    pharmacopoeia: "${r.pharmacopoeia}",
    titleZh: "${r.name} 入口探测（${r.ok ? "可达" : "不可达/超时"}）",
    titleEn: "${r.name} portal probe (${r.ok ? "reachable" : "unreachable"})",
    summaryZh: "scripts/fetch-alert-sources.mjs 可达性记录（status=${r.status}）。不代表专论正文变更。",
    summaryEn: "Reachability probe only; not monograph full text.",
    severity: "${r.ok ? "info" : "watch"}",
    officialUrl: "${r.url}",
    sourceKey: "${r.key}",
    demoLabel: true,
  }`);

const file = `import type { ChangeEvent } from "@/lib/types";

/** Generated by scripts/fetch-alert-sources.mjs — lastChecked ${now} */
export const CHANGE_EVENTS_LAST_CHECKED = "${now}";

export const generatedChangeEvents: ChangeEvent[] = [
${probeEvents.join(",\n")},
  {
    id: "ce-gen-seed-fda",
    date: "2026-06-01",
    pharmacopoeia: "FDA",
    titleZh: "FDA 亚硝胺指导页关注（富化种子）",
    titleEn: "FDA nitrosamine watch (enriched seed)",
    summaryZh: "网络失败时仍保留的富化种子；请核 FDA 现行文件。",
    summaryEn: "Enriched seed retained when network blocked.",
    relatedImpurityIds: ["imp-aspirin-ndma"],
    severity: "watch",
    officialUrl: "https://www.fda.gov/regulatory-information/search-fda-guidance-documents/control-nitrosamine-impurities-human-drugs",
    sourceKey: "fda-nitrosamine",
    demoLabel: true,
  },
];
`;

writeFileSync(outTs, file);
console.log("wrote", outTs);
if (existsSync(outTs)) console.log("bytes", readFileSync(outTs).length);
